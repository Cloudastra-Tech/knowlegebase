"""
db_pg.translate: the stores' SQLite SQL as Postgres runs it (platform.md PL-04).
Pure text in, text out: no database needed, so it runs on both CI legs.
"""

import pytest

pytest.importorskip("psycopg")

import db_pg  # noqa: E402

KEYS = {"chunk_contexts": ["hash"], "insights_daily": ["workspace", "day"]}
IDENTITY = {"jobs": "id", "audit_events": "id"}


def pg(sql, placeholders=True):
    return db_pg.translate(sql, KEYS.get, IDENTITY.get, placeholders).sql


def test_parameters_become_percent_s_and_a_literal_percent_is_doubled():
    assert pg("SELECT * FROM t WHERE a = ? AND b LIKE '%x'") == \
        "SELECT * FROM t WHERE a = %s AND b ILIKE '%%x'"
    assert pg("SELECT * FROM t WHERE a = :name") == "SELECT * FROM t WHERE a = %(name)s"
    assert pg("SELECT '50%' AS a", placeholders=False) == "SELECT '50%' AS a"


def test_a_question_mark_in_a_string_is_not_a_parameter():
    assert pg("SELECT 'why?' FROM t WHERE a = ?") == "SELECT 'why?' FROM t WHERE a = %s"


def test_an_empty_in_list_is_an_empty_subquery():
    assert pg("DELETE FROM d WHERE a = ? AND k NOT IN ()") == \
        "DELETE FROM d WHERE a = %s AND k NOT IN (SELECT NULL WHERE FALSE)"


def test_insert_or_ignore_and_or_replace():
    assert pg("INSERT OR IGNORE INTO workspaces (slug, name) VALUES (?, ?)") == \
        "INSERT INTO workspaces (slug, name) VALUES (%s, %s) ON CONFLICT DO NOTHING"
    assert pg("INSERT OR REPLACE INTO chunk_contexts (hash, model, context) VALUES (?, ?, ?)") \
        == ("INSERT INTO chunk_contexts (hash, model, context) VALUES (%s, %s, %s) "
            "ON CONFLICT (hash) DO UPDATE SET model = EXCLUDED.model, "
            "context = EXCLUDED.context")


def test_or_replace_resets_the_columns_it_leaves_out_and_needs_the_primary_key():
    settable = {"chunk_contexts": ["hash", "model", "context", "created_at"]}.get
    assert db_pg.translate(
        "INSERT OR REPLACE INTO chunk_contexts (hash, model) VALUES (?, ?)",
        KEYS.get, IDENTITY.get, True, lambda t: settable(t) or []).sql == \
        ("INSERT INTO chunk_contexts (hash, model) VALUES (%s, %s) ON CONFLICT (hash) DO "
         "UPDATE SET model = EXCLUDED.model, context = DEFAULT, created_at = DEFAULT")
    # Replacing on another unique key than the primary one: spelled out by the store.
    with pytest.raises(db_pg.NotSupported, match="without its primary key"):
        pg("INSERT OR REPLACE INTO chunk_contexts (model, context) VALUES (?, ?)")


def test_bare_columns_in_do_update_are_the_tables_own():
    assert pg("INSERT INTO s (workspace, version) VALUES (?, 1) ON CONFLICT(workspace) "
              "DO UPDATE SET version = version + 1, at = excluded.at") == \
        ("INSERT INTO s (workspace, version) VALUES (%s, 1) ON CONFLICT(workspace) "
         "DO UPDATE SET version = s.version + 1, at = excluded.at")
    assert pg("INSERT INTO u (a, b) VALUES (?, ?) ON CONFLICT (a) DO UPDATE SET "
              "b = COALESCE(excluded.b, b) WHERE u.a = excluded.a") == \
        ("INSERT INTO u (a, b) VALUES (%s, %s) ON CONFLICT (a) DO UPDATE SET "
         "b = COALESCE(excluded.b, u.b) WHERE u.a = excluded.a")


def test_is_against_a_value_is_distinct_from():
    assert pg("SELECT 1 FROM j WHERE s.workspace IS j.workspace AND x IS NOT NULL "
              "AND g IS NOT 'scim' AND y IS NULL") == \
        ("SELECT 1 FROM j WHERE s.workspace IS NOT DISTINCT FROM j.workspace AND "
         "x IS NOT NULL AND g IS DISTINCT FROM 'scim' AND y IS NULL")


def test_scalar_min_max_ifnull_and_user():
    assert pg("UPDATE jobs SET run_after = MIN(run_after, ?), n = MAX(n) WHERE id = ?") == \
        "UPDATE jobs SET run_after = LEAST(run_after, %s), n = MAX(n) WHERE id = %s"
    assert pg("SELECT IFNULL(a, 0), COUNT(DISTINCT user) FROM q WHERE user = ?") == \
        'SELECT COALESCE(a, 0), COUNT(DISTINCT "user") FROM q WHERE "user" = %s'


def test_an_insert_into_a_table_with_an_identity_returns_it():
    t = db_pg.translate("INSERT INTO jobs (kind) VALUES (?)", KEYS.get, IDENTITY.get)
    assert t.sql == "INSERT INTO jobs (kind) VALUES (%s) RETURNING id"
    assert t.returning_id == "id"
    assert db_pg.translate("INSERT INTO t (a) VALUES (?)", KEYS.get, IDENTITY.get).returning_id \
        is None


def test_ddl_types():
    assert pg("CREATE TABLE x (id INTEGER PRIMARY KEY AUTOINCREMENT, user TEXT, at REAL, "
              "b BLOB, n INTEGER NOT NULL DEFAULT 0)", placeholders=False) == \
        ('CREATE TABLE x (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY , '
         '"user" TEXT, at DOUBLE PRECISION, b BYTEA, n BIGINT NOT NULL DEFAULT 0)')


@pytest.mark.parametrize("sql", [
    "PRAGMA table_info(members)",
    "SELECT name FROM sqlite_master",
    "UPDATE OR REPLACE doc_acl SET principal = ?",
    "SELECT snippet(conversation_search, 0) FROM conversation_search",
    "SELECT * FROM s WHERE s MATCH ?",
    "SELECT strftime('%s', 'now')",
    "CREATE TRIGGER t AFTER DELETE ON m BEGIN SELECT 1; END",
])
def test_sqlite_only_sql_is_refused_by_name(sql):
    with pytest.raises(db_pg.NotSupported, match="SQLite|no Postgres|translation"):
        pg(sql)


def test_a_type_name_outside_ddl_is_only_a_type_in_a_cast():
    assert pg("SELECT secret AS blob, CAST(at AS INTEGER), CAST(x AS REAL) FROM t") == \
        "SELECT secret AS blob, CAST(at AS BIGINT), CAST(x AS DOUBLE PRECISION) FROM t"

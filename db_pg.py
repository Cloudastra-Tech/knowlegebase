# ---- Translation --------------------------------------------------------------------
_TOKEN = re.compile(r"""
    (?P<space>\s+)
  | (?P<comment>--[^\n]*|/\*.*?\*/)
  | (?P<string>'(?:[^']|'')*')
  | (?P<quoted>"(?:[^"]|"")*")
  | (?P<number>\d+(?:\.\d*)?(?:[eE][-+]?\d+)?)
  | (?P<word>[A-Za-z_][A-Za-z0-9_$]*)
  | (?P<param>\?\d*)
  | (?P<named>:[A-Za-z_][A-Za-z0-9_]*)
  | (?P<op>\|\||<>|!=|<=|>=|==|::|.)
""", re.X | re.S)

_REFUSED_WORDS = {
    "PRAGMA": "PRAGMA", "SQLITE_MASTER": "sqlite_master", "SQLITE_SCHEMA": "sqlite_schema",
    "SQLITE_SEQUENCE": "sqlite_sequence", "MATCH": "FTS5 MATCH", "GLOB": "GLOB",
    "ATTACH": "ATTACH", "DETACH": "DETACH", "VACUUM": "VACUUM", "VIRTUAL": "virtual tables",
    "TRIGGER": "triggers (CREATE TRIGGER)", "WITHOUT": "WITHOUT ROWID",
}
_REFUSED_FUNCTIONS = {
    "SNIPPET", "BM25", "HIGHLIGHT", "JSON", "JSON_EXTRACT", "JSON_EACH", "JSON_OBJECT",
    "JSON_ARRAY", "JSON_SET", "JSON_GROUP_ARRAY", "STRFTIME", "DATETIME", "JULIANDAY",
    "DATE", "TIME", "UNIXEPOCH", "PRINTF", "TYPEOF", "CHANGES", "LAST_INSERT_ROWID",
    "TOTAL_CHANGES", "RANDOMBLOB", "INSTR", "IIF", "GROUP_CONCAT", "TOTAL",
}
_TYPES = {"INTEGER": "BIGINT", "REAL": "DOUBLE PRECISION", "BLOB": "BYTEA"}
_IS_KEEP = {"NULL", "TRUE", "FALSE", "DISTINCT", "UNKNOWN", "NOT"}
# Words in a DO UPDATE SET expression that are not columns.
_SQL_WORDS = {
    "NULL", "TRUE", "FALSE", "AND", "OR", "NOT", "IS", "IN", "CASE", "WHEN", "THEN", "ELSE",
    "END", "DISTINCT", "FROM", "LIKE", "ILIKE", "BETWEEN", "CAST", "AS", "COLLATE", "NOCASE",
    "ESCAPE", "WHERE", "EXCLUDED", "BIGINT", "TEXT", "DOUBLE", "PRECISION", "BYTEA",
    "INTEGER", "REAL", "CURRENT_TIMESTAMP", "INTERVAL",
}

Translated = collections.namedtuple("Translated", "sql kind table returning_id")


def _tokens(sql):
    return [[m.lastgroup, m.group()] for m in _TOKEN.finditer(sql)]


def _sig(toks, i, step=1):
    """Index of the next token (from i, i included) that isn't space or a comment."""
    while 0 <= i < len(toks) and toks[i][0] in ("space", "comment"):
        i += step
    return i if 0 <= i < len(toks) else None


def _word(toks, i):
    return toks[i][1].upper() if i is not None and toks[i][0] == "word" else None


def _close(toks, i):
    """Index of the ) matching the ( at i."""
    depth = 0
    for j in range(i, len(toks)):
        if toks[j][1] == "(":
            depth += 1
        elif toks[j][1] == ")":
            depth -= 1
            if depth == 0:
                return j
    raise NotSupported("unbalanced parentheses")


def _snippet(sql):
    text = " ".join(sql.split())
    return text if len(text) <= 120 else text[:117] + "..."


def translate(sql, primary_keys=None, identity=None, placeholders=True):
    """`sql` (SQLite's dialect) as Postgres runs it: a Translated(sql, kind, table,
    returning_id). primary_keys(table) / identity(table): the catalog, for INSERT
    OR REPLACE and lastrowid. placeholders: ? becomes %s and % is doubled (for a
    statement run with parameters)."""
    toks = _tokens(sql)
    first = _sig(toks, 0)
    kind = _word(toks, first) or ""
    if kind == "REPLACE":                              # REPLACE INTO = INSERT OR REPLACE
        toks[first:first + 1] = _tokens("INSERT OR REPLACE")
        kind = "INSERT"
    conflict = table = alias = None
    columns = []

    # INSERT OR IGNORE / OR REPLACE; UPDATE OR ... has no translation.
    if kind in ("INSERT", "UPDATE"):
        j = _sig(toks, first + 1)
        if _word(toks, j) == "OR":
            k = _sig(toks, j + 1)
            how = _word(toks, k)
            if kind == "UPDATE" or how not in ("IGNORE", "REPLACE"):
                raise NotSupported(f"{kind} OR {how} has no Postgres translation "
                                   f"(in: {_snippet(sql)})")
            conflict = how
            for n in range(first + 1, k + 1):
                toks[n] = ["space", ""]
    if kind == "INSERT":
        j = _sig(toks, first + 1)
        if _word(toks, j) == "INTO":
            t = _sig(toks, j + 1)
            table = toks[t][1].strip('"')
            a = _sig(toks, t + 1)
            if _word(toks, a) == "AS":
                alias = toks[_sig(toks, a + 1)][1]
                a = _sig(toks, _sig(toks, a + 1) + 1)
            if a is not None and toks[a][1] == "(":
                columns = [toks[n][1].strip('"') for n in range(a + 1, _close(toks, a))
                           if toks[n][0] in ("word", "quoted")]

    out = []
    in_set = False                    # inside ON CONFLICT ... DO UPDATE SET ... [WHERE ...]
    depth = 0                         # parentheses deep, in there
    target = False                    # the next identifier is a SET target column
    returning_at = None
    for i, (kind_, text) in enumerate(toks):
        up = text.upper()
        if kind_ in ("word", "quoted"):
            nxt = _sig(toks, i + 1)
            prev = _sig(toks, i - 1, -1)
            called = nxt is not None and toks[nxt][1] == "("
            dotted = (prev is not None and toks[prev][1] == ".") or \
                (nxt is not None and toks[nxt][1] == ".")
            column = kind_ == "quoted" or (not called and up not in _SQL_WORDS)
            if kind_ == "word":
                if up in _REFUSED_WORDS and not dotted and \
                        (up != "WITHOUT" or _word(toks, nxt) == "ROWID"):
                    raise NotSupported(f"{_REFUSED_WORDS[up]} is SQLite-only "
                                       f"(in: {_snippet(sql)})")
                if called and up in _REFUSED_FUNCTIONS and not dotted:
                    raise NotSupported(f"SQLite's {text.lower()}() has no Postgres "
                                       f"translation (in: {_snippet(sql)})")
                if up == "RETURNING" and depth == 0:
                    returning_at, in_set = len(out), False
                elif up == "WHERE" and in_set and depth == 0:
                    target = False
                elif up == "SET" and not in_set and _word(toks, prev) == "UPDATE" and \
                        _word(toks, _sig(toks, prev - 1, -1)) == "DO":
                    in_set, depth, target = True, 0, True
                    column = False
                if up == "USER" and not called:
                    text = '"user"'
                elif up == "IFNULL" and called:
                    text = "COALESCE"
                elif up == "CHAR" and called:
                    text = "chr"
                elif up == "LIKE":
                    text = "ILIKE"
                elif up in ("MIN", "MAX") and called:
                    level = 0
                    for n in range(nxt, _close(toks, nxt)):
                        level += {"(": 1, ")": -1}.get(toks[n][1], 0)
                        if toks[n][1] == "," and level == 1:
                            text = "LEAST" if up == "MIN" else "GREATEST"
                            break
                elif up == "IS":
                    if _word(toks, nxt) == "NOT":
                        if _word(toks, _sig(toks, nxt + 1)) not in _IS_KEEP:
                            text = "IS DISTINCT FROM"
                            for n in range(i + 1, nxt + 1):      # NOT, and the space before
                                toks[n] = ["space", ""]
                    elif _word(toks, nxt) not in _IS_KEEP:
                        text = "IS NOT DISTINCT FROM"
                elif up == "INTEGER" and not dotted:
                    k = _sig(toks, i + 1)
                    text = "BIGINT GENERATED BY DEFAULT AS IDENTITY" if (
                        _word(toks, k) == "PRIMARY" and _word(toks, _sig(toks, k + 1)) == "KEY"
                    ) else "BIGINT"
                elif up in _TYPES and not called and not dotted:
                    text = _TYPES[up]
                elif up == "AUTOINCREMENT":
                    text = ""
            if in_set and column and not dotted and up not in ("SET", "WHERE"):
                if target:
                    target = False
                else:
                    text = f"{alias or table}.{text}"
        elif kind_ == "op":
            if text == "==":
                text = "="
            elif text == "(" and _word(toks, _sig(toks, i - 1, -1)) == "IN" and \
                    toks[_sig(toks, i + 1)][1] == ")":
                text = "(SELECT NULL WHERE FALSE"      # SQLite's x [NOT] IN (): an empty list
            elif in_set and text == "(":
                depth += 1
            elif in_set and text == ")":
                depth -= 1
            elif in_set and text == "," and depth == 0:
                target = True
            if placeholders and text == "%":
                text = "%%"
        elif kind_ == "param":
            if text != "?":
                raise NotSupported(f"numbered parameters ({text}) aren't supported "
                                   f"(in: {_snippet(sql)})")
            if placeholders:
                text = "%s"
        elif kind_ == "named":
            if placeholders:
                text = f"%({text[1:]})s"
        elif placeholders and kind_ in ("string", "comment") and "%" in text:
            text = text.replace("%", "%%")
        out.append(text)

    tail = []
    if conflict == "IGNORE":
        tail.append("ON CONFLICT DO NOTHING")
    elif conflict == "REPLACE":
        keys = primary_keys(table) if primary_keys else None
        if not keys:
            raise NotSupported(f"INSERT OR REPLACE INTO {table}: no primary key known")
        updates = [c for c in columns if c not in keys]
        tail.append(f"ON CONFLICT ({', '.join(_ident(k) for k in keys)}) DO "
                    + ("UPDATE SET " + ", ".join(f"{_ident(c)} = EXCLUDED.{_ident(c)}"
                                                  for c in updates) if updates else "NOTHING"))
    returning_id = None
    if kind == "INSERT" and returning_at is None and identity and table:
        returning_id = identity(table)
        if returning_id:
            tail.append(f"RETURNING {_ident(returning_id)}")
    if returning_at is not None:
        out[returning_at:returning_at] = [t + " " for t in tail]
        text = "".join(out)
    else:
        text = " ".join(["".join(out).rstrip().rstrip(";").rstrip()] + tail)
    return Translated(text, kind, table, returning_id)


def _ident(name):
    return f'"{name}"' if name.lower() == "user" or not re.fullmatch(r"[a-z_][a-z0-9_]*", name) \
        else name


# ---- Values -------------------------------------------------------------------------
class _NumericLoader(Loader):
    """numeric (e.g. SUM of integers) as int or float, as SQLite returns it."""

    def load(self, data):
        text = bytes(data).decode()
        try:
            return int(text)
        except ValueError:
            return float(text)


class _BoolLoader(Loader):
    def load(self, data):
        return 1 if bytes(data) in (b"t", b"\x01") else 0


class _BoolDumper(Dumper):
    """True / False as 1 / 0: the columns are integers, as in SQLite."""
    oid = psycopg.adapters.types["int8"].oid

    def dump(self, obj):
        return b"1" if obj else b"0"


def _configure(conn):
    conn.adapters.register_loader("numeric", _NumericLoader)
    conn.adapters.register_loader("bool", _BoolLoader)
    conn.adapters.register_dumper(bool, _BoolDumper)


class Row:
    """A result row as sqlite3.Row: row["name"] (any case), row[0], keys(), dict(row)."""
    __slots__ = ("_names", "_index", "_values")

    def __init__(self, names, index, values):
        self._names, self._index, self._values = names, index, values

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return self._values[key]
        i = self._index.get(key)
        if i is None:
            i = self._index.get(str(key).lower())
        if i is None:
            raise IndexError("No item with that key")
        return self._values[i]

    def keys(self):
        return list(self._names)

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def __eq__(self, other):
        if isinstance(other, Row):
            return self._names == other._names and self._values == other._values
        return NotImplemented

    def __hash__(self):
        return hash((self._names, tuple(self._values)))

    def __repr__(self):
        return f"<Row {dict(zip(self._names, self._values))!r}>"


def _row_factory(cursor):
    desc = cursor.description
    if desc is None:
        return tuple
    names = tuple(c.name for c in desc)
    index = {}
    for i, name in enumerate(names):
        index.setdefault(name, i)
        index.setdefault(name.lower(), i)
    return lambda values: Row(names, index, values)


def _tuple_factory(cursor):
    return tuple


def _sqlite_error(e, sql=None):
    """psycopg's error as the sqlite3 class the stores catch."""
    if isinstance(e, pg_errors.IntegrityError):
        cls = sqlite3.IntegrityError
    elif isinstance(e, pg_errors.DataError):
        cls = sqlite3.DataError
    elif isinstance(e, (pg_errors.OperationalError, pg_errors.ProgrammingError)):
        cls = sqlite3.OperationalError
    elif isinstance(e, pg_errors.NotSupportedError):
        cls = sqlite3.NotSupportedError
    else:
        cls = sqlite3.DatabaseError
    err = cls(str(e).strip())
    err.sqlstate = getattr(e, "sqlstate", None)
    return err


# ---- The catalog ----------------------------------------------------------------------
class Catalog:
    """Primary keys and identity columns of the database's tables, read once (and
    again after a migration)."""

    def __init__(self):
        self._lock = threading.Lock()
        self._keys = self._identity = None
        self.translations = {}

    def forget(self):
        with self._lock:
            self._keys = self._identity = None
            self.translations = {}

    def load(self, raw):
        with self._lock:
            if self._keys is not None:
                return
            keys, identity = {}, {}
            for table, column in raw.execute(
                    """SELECT tc.table_name, kcu.column_name
                         FROM information_schema.table_constraints tc
                         JOIN information_schema.key_column_usage kcu
                           ON kcu.constraint_name = tc.constraint_name
                          AND kcu.table_schema = tc.table_schema
                          AND kcu.table_name = tc.table_name
                        WHERE tc.constraint_type = 'PRIMARY KEY'
                          AND tc.table_schema = current_schema()
                        ORDER BY tc.table_name, kcu.ordinal_position""").fetchall():
                keys.setdefault(table, []).append(column)
            for table, column in raw.execute(
                    """SELECT table_name, column_name FROM information_schema.columns
                        WHERE table_schema = current_schema() AND is_identity = 'YES'
                          AND column_name <> 'rowid'""").fetchall():
                identity[table] = column
            self._keys, self._identity = keys, identity

    def primary_keys(self, table):
        return (self._keys or {}).get(table)

    def identity(self, table):
        return (self._identity or {}).get(table)

    def translate(self, sql, placeholders=True):
        key = (sql, placeholders)
        hit = self.translations.get(key)
        if hit is None:
            hit = translate(sql, self.primary_keys, self.identity, placeholders)
            if len(self.translations) > 4096:
                self.translations.clear()
            self.translations[key] = hit
        return hit


# ---- Connections ----------------------------------------------------------------------
class Database:
    """One Postgres database: its pool of connections and its catalog."""

    def __init__(self, url):
        self.url = url
        self.catalog = Catalog()
        self._lock = threading.Lock()
        self._pool = None
        self.tenant_role = None          # the role tenants run as, once known to exist
        self._set = weakref.WeakKeyDictionary()    # pooled connection -> (role, workspace)

    def pool(self):
        with self._lock:
            if self._pool is None:
                self._pool = ConnectionPool(self.url, min_size=1, max_size=POOL_MAX,
                                            timeout=POOL_TIMEOUT, open=True,
                                            kwargs={"autocommit": True},
                                            configure=_configure, name="kb-db")
            return self._pool

    def close(self):
        with self._lock:
            if self._pool is not None:
                self._pool.close()
                self._pool = None

    def refresh(self, raw):
        """After a migration: read the catalog again, and whether the tenant role exists."""
        self.catalog.forget()
        self.catalog.load(raw)
        self.tenant_role = TENANT_ROLE if raw.execute(
            "SELECT 1 FROM pg_roles WHERE rolname = %s", (TENANT_ROLE,)).fetchone() else None

    def connect(self, workspace=None):
        if self.catalog._keys is None:
            raw = self.checkout(None)
            self.put(raw)
        tenant = workspace if workspace and self.tenant_role else None
        return Connection(self, tenant)

    def checkout(self, workspace):
        """A pooled connection, running as `workspace`'s tenant (or the platform)."""
        raw = self.pool().getconn()
        try:
            if self.catalog._keys is None:
                raw.execute("RESET ROLE")
                self._set.pop(raw, None)
                self.refresh(raw)
            want = (self.tenant_role if workspace else "none", workspace or "")
            if self._set.get(raw) != want:
                raw.execute("SELECT set_config('role', %s, false), "
                            "set_config('app.workspace', %s, false)", want)
                self._set[raw] = want
        except BaseException:
            self.pool().putconn(raw)
            raise
        return raw

    def put(self, raw):
        pool = self._pool
        if pool is None:
            raw.close()
            return
        try:
            if not raw.closed and raw.info.transaction_status != TransactionStatus.IDLE:
                raw.execute("ROLLBACK")
        except psycopg.Error:
            raw.close()
        pool.putconn(raw)


class Cursor:
    """What Connection.execute returns: fetchone / fetchall / iteration, rowcount,
    lastrowid, description. The rows are read at once: the connection goes back to
    the pool as soon as a statement outside a transaction is done."""

    def __init__(self, conn):
        self.connection = conn
        self.rowcount = -1
        self.lastrowid = None
        self.arraysize = 1
        self.description = None
        self._rows = []

    def _run(self, sql, params, many=False):
        conn = self.connection
        head = sql.lstrip().split(None, 2)
        verb = head[0].upper().rstrip(";") if head else ""
        if verb in ("BEGIN", "COMMIT", "END", "ROLLBACK") and not many and \
                not (verb == "ROLLBACK" and len(head) > 1 and head[1].upper() == "TO"):
            conn._control(verb, sql)
            return self
        one = params[0] if many and params else params
        named = isinstance(one, collections.abc.Mapping)
        t = conn._db.catalog.translate(sql, placeholders=True)
        raw = conn._acquire()
        try:
            dml = t.kind in ("INSERT", "UPDATE", "DELETE")
            if dml and conn.isolation_level is not None and not conn.in_transaction:
                raw.execute("BEGIN")
                savepoint = False
            else:
                savepoint = conn.in_transaction
            cur = raw.cursor(row_factory=conn.row_factory_for())
            if savepoint:
                raw.execute("SAVEPOINT kb_statement")
            try:
                if many:
                    cur.executemany(t.sql, [p if named else tuple(p) for p in params])
                else:
                    cur.execute(t.sql, params if named else tuple(params or ()))
            except psycopg.Error as e:
                if savepoint:
                    raw.execute("ROLLBACK TO SAVEPOINT kb_statement")
                    raw.execute("RELEASE SAVEPOINT kb_statement")
                elif raw.info.transaction_status == TransactionStatus.INERROR:
                    raw.execute("ROLLBACK")
                raise _sqlite_error(e, sql) from e
            if savepoint:
                raw.execute("RELEASE SAVEPOINT kb_statement")
            self.rowcount = cur.rowcount if dml else -1
            self.description = cur.description
            rows = cur.fetchall() if cur.description is not None else []
            cur.close()
            if t.returning_id and not many:
                self.lastrowid = rows[0][0] if rows else None
                rows, self.description = [], None
            self._rows = rows
        finally:
            conn._release()
        return self

    def execute(self, sql, params=()):
        return self._run(sql, params)

    def executemany(self, sql, seq):
        return self._run(sql, list(seq), many=True)

    def fetchone(self):
        return self._rows.pop(0) if self._rows else None

    def fetchall(self):
        rows, self._rows = self._rows, []
        return rows

    def fetchmany(self, size=None):
        n = size or self.arraysize
        rows, self._rows = self._rows[:n], self._rows[n:]
        return rows

    def __iter__(self):
        return iter(self.fetchall())

    def close(self):
        self._rows = []


class Connection:
    """A Postgres connection that behaves like a sqlite3 connection (see the top of
    this file). It holds a connection from the pool only while a transaction is
    open: a statement outside one borrows one and gives it back, so a connection
    object left open (sqlite3 lets the stores do that) never ties up the pool."""

    def __init__(self, database, workspace=None):
        self._db = database
        self._raw = None
        self._closed = False
        self.workspace = workspace          # the tenant it is limited to (None: platform)
        self.isolation_level = ""           # sqlite3's default: writes open a transaction
        self.row_factory = sqlite3.Row      # what the stores set; Row is what they get

    def _acquire(self):
        if self._closed:
            raise sqlite3.ProgrammingError("Cannot operate on a closed database.")
        if self._raw is None:
            self._raw = self._db.checkout(self.workspace)
        return self._raw

    def _release(self):
        """Back to the pool, unless a transaction is open."""
        raw = self._raw
        if raw is not None and (raw.closed or
                                raw.info.transaction_status == TransactionStatus.IDLE):
            self._raw = None
            self._db.put(raw)

    def _raw_conn(self):
        """The pooled connection itself, held until close() (for SQL of Postgres's
        own that must run on one session)."""
        return self._acquire()

    def row_factory_for(self):
        return _row_factory if self.row_factory is not None else _tuple_factory

    @property
    def in_transaction(self):
        return self._raw is not None and \
            self._raw.info.transaction_status != TransactionStatus.IDLE

    def _control(self, verb, sql):
        if verb == "BEGIN":
            if self.in_transaction:
                raise sqlite3.OperationalError("cannot start a transaction within a transaction")
            raw = self._acquire()
            raw.execute("BEGIN")
            if re.search(r"\b(IMMEDIATE|EXCLUSIVE)\b", sql, re.I):
                raw.execute("SELECT pg_advisory_xact_lock(%s)", (WRITE_LOCK,))
        elif verb in ("COMMIT", "END"):
            self.commit()
        else:
            self.rollback()

    def execute(self, sql, params=()):
        return Cursor(self).execute(sql, params)

    def executemany(self, sql, seq):
        return Cursor(self).executemany(sql, seq)

    def cursor(self):
        return Cursor(self)

    def executescript(self, script):
        raise NotSupported("executescript() is SQLite-only")

    def create_function(self, *args, **kwargs):
        raise NotSupported("create_function() is SQLite-only: compute it in Python "
                           "or in SQL on Postgres")

    def commit(self):
        if self.in_transaction:
            try:
                self._raw.execute("COMMIT")
            except psycopg.Error as e:
                raise _sqlite_error(e) from e
            finally:
                self._release()

    def rollback(self):
        if self.in_transaction:
            try:
                self._raw.execute("ROLLBACK")
            finally:
                self._release()

    def close(self):
        self._closed = True
        raw, self._raw = self._raw, None
        if raw is not None:
            self._db.put(raw)

    def __enter__(self):
        return self

    def __exit__(self, kind, value, tb):
        if kind is None:
            self.commit()
        else:
            self.rollback()
        return False

    def __del__(self):
        try:
            self.close()
        except Exception:              # at interpreter exit, the pool may be gone
            pass


_databases = {}
_databases_lock = threading.Lock()


def database(url):
    with _databases_lock:
        found = _databases.get(url)
        if found is None:
            found = _databases[url] = Database(url)
        return found


def close_all():
    with _databases_lock:
        for found in _databases.values():
            found.close()
        _databases.clear()


@contextlib.contextmanager
def raw_connection(url, autocommit=True):
    """A plain psycopg connection (no pool, no translation): migrations' own steps,
    tools and tests."""
    conn = psycopg.connect(url, autocommit=autocommit)
    try:
        yield conn
    finally:
        conn.close()

"""
db_pg.py  —  Postgres behind db.connect(), when DATABASE_URL is a postgresql:// URL
(platform.md PL-04). SQLite stays the default; see db.py.

The stores were written against sqlite3, and keep their SQL: a Connection from
here behaves like a sqlite3 connection in everything they use.

    rows          Row: by name (row["role"]) or position, dict(row), row.keys()
    parameters    ? placeholders (and :name with a dict), sent as %s
    lastrowid     an INSERT into a table with an identity column (an
                  INTEGER PRIMARY KEY in SQLite) gets RETURNING it
    rowcount      as sqlite3's
    transactions  as sqlite3's default mode: a write (INSERT, UPDATE, DELETE)
                  opens a transaction when none is open, and commit(), rollback()
                  or `with conn:` end it; isolation_level = None turns that off
                  (BEGIN / COMMIT by hand). BEGIN IMMEDIATE is BEGIN plus a
                  transaction-level advisory lock: one such writer at a time, as
                  SQLite's write lock. A statement that fails inside a
                  transaction is undone alone (a savepoint), as in SQLite, not
                  the whole transaction.
    errors        psycopg's raised as sqlite3's classes (IntegrityError,
                  OperationalError, ...): what the stores catch
    values        numeric (SUM of integers) comes back as int or float, never
                  Decimal; booleans go in and come out as 1 / 0

translate() turns SQLite SQL into Postgres SQL:

    INSERT OR IGNORE           INSERT ... ON CONFLICT DO NOTHING
    INSERT OR REPLACE          INSERT ... ON CONFLICT (primary key) DO UPDATE
    ON CONFLICT DO UPDATE SET  bare columns on the right named by their table
                               (Postgres finds them ambiguous with `excluded`)
    a IS b / a IS NOT b        IS [NOT] DISTINCT FROM (b not NULL, TRUE, FALSE)
    MIN(a, b) / MAX(a, b)      LEAST / GREATEST
    IFNULL, char()             COALESCE, chr()
    LIKE                       ILIKE (SQLite's LIKE ignores case)
    user                       "user" (a reserved word in Postgres)
    INTEGER PRIMARY KEY [AUTOINCREMENT]   BIGINT GENERATED BY DEFAULT AS IDENTITY
    INTEGER, REAL, BLOB        BIGINT, DOUBLE PRECISION, BYTEA
    COLLATE NOCASE             unchanged: the migrations make a `nocase` collation
                               (ICU, case-insensitive)

and refuses, with NotSupported naming what it found, SQL that has no
translation: PRAGMA, sqlite_master, FTS5 (MATCH, snippet, bm25), triggers,
virtual tables, UPDATE OR ..., SQLite's date and JSON functions. Code that needs
one of those has a Postgres branch of its own (db.is_postgres()).

ROW-LEVEL SECURITY. Connections opened inside db.tenant_scope() for a workspace
run as the tenant role (DB_TENANT_ROLE, default kb_tenant) with app.workspace
set to it: Postgres then shows and accepts only that workspace's rows of every
tenant table (migrations/postgres.py makes the policies). Anything else runs as
the login role, which owns the tables and so is not limited by them (the
platform role: jobs of no workspace, the operator, sign-in before the workspace
is known).
"""

